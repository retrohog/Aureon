#!/usr/bin/env python3
"""Designs the noise-transfer functions of Aureon's 1-bit PCM -> DSD modulators and prints them as Swift source.

For each (order, oversampling ratio) it places the zeros at the roots of the Legendre polynomial across the audio band (the placement that
minimises in-band noise power), takes the poles of a Butterworth high-pass, and moves its cut-off until the out-of-band gain (Hinf) reaches the
target: Lee's rule of thumb says a one-bit loop stays stable for Hinf <= 1.5, and the table keeps some margin below that. The script then
checks each design by running the loop it describes (error-feedback form, double precision, the arithmetic the Swift code uses) on a full-scale test
tone, and refuses to emit a design that overloads.

    python3 design_ntf.py > ../../Sources/Aureon/Pipeline/ModulatorTables.swift
"""
import sys
import numpy as np
from numpy.polynomial import legendre
from scipy import signal

ORDERS = (5, 7)
OSRS = (64, 128, 256, 512)           # DSD64, DSD128, DSD256, DSD512 for the 44.1 kHz family (48 kHz family has the same ratios)
HINF = {5: 1.40, 7: 1.35}            # target out-of-band gain per order


def zeros_for(order, osr):
    nodes = np.sort(legendre.leggauss(order)[0])             # Gauss-Legendre nodes: 0 and symmetric pairs for odd order
    wb = np.pi / osr
    z = []
    for r in nodes:
        a = wb * r
        z.append(np.exp(1j * a))
    return np.array(z)


def hinf_of(b, a):
    w, h = signal.freqz(b, a, worN=8192)
    return np.max(np.abs(h))


def design(order, osr, target):
    zs = zeros_for(order, osr)
    b = np.real(np.poly(zs))
    lo, hi = 1e-4, 0.9
    best = None
    for _ in range(80):
        wn = (lo * hi) ** 0.5
        bb, aa = signal.butter(order, wn, btype="high")
        # Butterworth high-pass has all zeros at z=1; keep its poles only
        pol = np.roots(aa)
        a = np.real(np.poly(pol))
        h = hinf_of(b, a)
        if h > target:
            hi = wn
        else:
            lo = wn
            best = (b, a, wn, h)
    return best


def simulate(b, a, osr, n, amp, freq_bins=None, seed=1):
    """Error-feedback loop, transposed direct form II. Returns (bits, max |state|, resets)."""
    N = len(b) - 1
    B = b[1:].copy(); A = a[1:].copy()
    w = np.zeros(N)
    rng = np.random.default_rng(seed)
    out = np.empty(n)
    peak = 0.0
    for i in range(n):
        x = amp * np.sin(2 * np.pi * 1000.0 / 44100.0 / (osr) * i) if freq_bins is None else amp * np.sin(2 * np.pi * freq_bins * i / n)
        s = w[0]
        v = x + s
        y = 1.0 if v >= 0 else -1.0
        e = y - v
        u = y - x
        w[:-1] = w[1:] + B[:-1] * e - A[:-1] * u
        w[-1] = B[-1] * e - A[-1] * u
        out[i] = y
        if abs(v) > peak: peak = abs(v)
    return out, peak


def swift_array(name, v):
    return "    " + name + ": [" + ", ".join(repr(float(x)) for x in v) + "]"


def main():
    print("// Generated by Tools/modulator/design_ntf.py. Do not edit by hand.")
    print("// Noise-transfer functions of the one-bit modulators: numerator b and denominator a of NTF(z) = b(z) / a(z), both monic,")
    print("// stored without the leading 1 (b1…bN, a1…aN).")
    print("enum ModulatorTables {")
    print("    struct Entry { let order: Int; let osr: Int; let b: [Double]; let a: [Double]; let hinf: Double }")
    print("    static let entries: [Entry] = [")
    for order in ORDERS:
        for osr in OSRS:
            b, a, wn, h = design(order, osr, HINF[order])
            print(f"        // order {order}, OSR {osr}: cut-off {wn:.5f}, Hinf {h:.3f}", flush=True)
            print(f"        Entry(order: {order}, osr: {osr},", flush=True)
            print("              b: [" + ", ".join(repr(float(x)) for x in b[1:]) + "],")
            print("              a: [" + ", ".join(repr(float(x)) for x in a[1:]) + f"], hinf: {float(h)!r}),")
    print("    ]")
    print("}")


if __name__ == "__main__":
    main()
